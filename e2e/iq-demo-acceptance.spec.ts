import { test, expect, type Page } from "@playwright/test";
import { readFileSync, existsSync } from "node:fs";
const baseURL = "http://localhost:3000";
const folder = process.env.OPS_IQ_DEMO_BACKUP ?? "/tmp/ops-iq-demo-backup";
const available = Boolean(process.env.OPS_IQ_DEMO_BACKUP && existsSync(`${folder}/local-storage-after.json`) && existsSync(`${folder}/prepared-rebuild.json`));
const snapshot = available ? JSON.parse(readFileSync(`${folder}/local-storage-after.json`, "utf8")) : { origin: baseURL, storage: {} };
const manifest = available ? JSON.parse(readFileSync(`${folder}/prepared-rebuild.json`, "utf8")) : { created: { auditIds: [], clientId: "" } };
test.skip(!available, "Opt in with OPS_IQ_DEMO_BACKUP pointing to the private completed demo snapshot");
if (snapshot.origin !== baseURL) throw new Error("Acceptance requires the private localhost demo snapshot");
test.use({ baseURL, actionTimeout: 10_000, storageState: { cookies: [], origins: [{ origin: baseURL, localStorage: [...Object.entries(snapshot.storage as Record<string, string>).map(([name, value]) => ({ name, value })), { name: "5s-auth-session", value: JSON.stringify({ authenticated: true, username: "admin", version: 1 }) }] }] } });
async function identity(page: Page, name: string) {
  await page.getByRole("button", { name: "Account menu", exact: true }).click();
  await page.getByRole("menuitem").filter({ hasText: "OPS Super Admin" }).click();
  await page.getByRole("button", { name: "Account menu", exact: true }).click();
  await page.getByRole("menuitem").filter({ has: page.getByText(name, { exact: true }), hasText: "Scoped OPS demo" }).click();
  await page.goto("/settings/administration");
  await page.getByRole("combobox", { name: "Active context", exact: true }).click();
  await page.getByRole("option", { name: "IQ · IQ Factory 1", exact: true }).click();
}
test("rebuilt IQ demo: preserved records, owner evidence, independent review and denied foreign task", async ({ page }) => {
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  page.on("console", m => { if (m.type() === "error" || /hydration|Base UI.*warning/i.test(m.text())) errors.push(m.text()); });
  await page.goto("/audits");
  await expect(page.getByText("IQ demo · Generated disposable data · Production activation is not authorized", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Restore demo data", exact: true })).toBeDisabled();
  await page.goto(`/audits?audit=${manifest.created.auditIds[0]}`);
  await expect(page.getByText("Remove unused assembly fixtures", { exact: true }).first()).toBeVisible();
  await page.getByRole("button", { name: /View Action/ }).first().click();
  await expect(page).toHaveURL(/\/actions\/ACT-/);
  const href = new URL(page.url()).pathname;
  await expect(page.getByRole("link", { name: "Open originating Audit", exact: true })).toBeVisible();
  await identity(page, "Suresh"); await page.goto(href);
  await expect(page.getByRole("link", { name: "Open originating Audit", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Corrective Action", exact: true }).click();
  await page.getByRole("button", { name: "Start work", exact: true }).click();
  await page.getByLabel("Resolution notes", { exact: true }).fill("Demo acceptance repair complete");
  await page.getByLabel("Corrective action category", { exact: true }).fill("Workplace Organization");
  await page.getByRole("button", { name: "Save work", exact: true }).click();
  await expect(page.getByLabel("Upload resolution evidence", { exact: true })).toBeEnabled();
  await page.getByLabel("Upload resolution evidence", { exact: true }).setInputFiles({ name: "iq-demo-proof.txt", mimeType: "text/plain", buffer: Buffer.from("Disposable acceptance evidence") });
  await expect(page.getByRole("button", { name: "iq-demo-proof.txt · resolution", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Submit for independent review", exact: true }).click();
  await expect(page.getByText(/Pending Auditor Review · Owner Suresh/)).toBeVisible();
  await identity(page, "Anand"); await page.goto(href);
  await expect(page.getByRole("heading", { name: "Operational context unavailable", exact: true })).toBeVisible();
  await identity(page, "Priya Raman"); await page.goto(href);
  await page.getByLabel("Review / rework reason", { exact: true }).fill("Verified independently in disposable acceptance context");
  await page.getByRole("button", { name: "Verify and close", exact: true }).click();
  await expect(page.getByText(/Completed · Owner Suresh/)).toBeVisible();
  await page.reload(); await expect(page.getByText(/Completed · Owner Suresh/)).toBeVisible();
  const persisted = await page.evaluate(() => ({ actions: JSON.parse(localStorage.getItem("standalone-5s-actions")!), audits: JSON.parse(localStorage.getItem("manufacturing-qms-five-s-audits-v1")!) }));
  expect(persisted.actions.filter((a: { organizationId?: string }) => a.organizationId === manifest.created.clientId)).toHaveLength(3);
  expect(persisted.audits.filter((a: { organizationId?: string }) => a.organizationId === manifest.created.clientId)).toHaveLength(2);
  await page.screenshot({ path: "/tmp/ops-iq-demo-accepted.png", fullPage: true });
  expect(errors).toEqual([]);
});
